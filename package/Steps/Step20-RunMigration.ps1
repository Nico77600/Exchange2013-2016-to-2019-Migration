<#
.SYNOPSIS
    Step 20 - Start the move requests (manual completion mode).

.DESCRIPTION
    How it works:
        - Reads MigrationPlan.csv generated by step 19.
        - Removes all existing MoveRequests before submitting.
        - Assigns a TargetDatabase to each MoveRequest, round-robin over the
          available Exchange 2019 databases.
        - New-MoveRequest with -SuspendWhenReadyToComplete: the synchronization
          runs but the completion must be triggered manually (Step21).
        - Generates MigrationStatus.html at the end of the Apply.

    Follow mode (FOLLOW):
        - Set $env:FOLLOW = '1' before running to enter follow mode.
        - In this mode, no migration action is performed.
        - An HTML report MigrationStatus.html is generated with the current state
          of all MoveRequests, by batch and by mailbox.
        - Can be used in Inventory or Apply mode alike.

    Re-run in Apply mode:
        - All existing MoveRequests are removed before the re-submission
          (clean slate, including the Completed MRs from previous steps).
        - Idempotent: running it several times gives the same final result.

    v1.4 - Single-batch focus mode (triggered by Step21 -FollowAfter -BatchNumber NN):
        - Read via $Global:FollowBatchFilter = 'BatchNN' set by the orchestrator.
        - Get-OfficialMigrationBatches: restricted to a single batch via
          Get-MigrationBatch -Identity BatchNN (server-side filter).
        - Get-MbSnapshot: Get-MoveRequest -BatchName 'MigrationService:BatchNN'
          instead of a full Get-MoveRequest + client-side filter (about 10x faster
          on 455 MRs).
        - The generated HTML uses a dedicated name: MigrationStatus-BatchNN.html
          (allows 2 FOLLOW sessions in parallel - global + focus - without collision).
        - The HTML title explicitly mentions "(focus)".

    v1.4 - Quarantined UI / Synced palette:
        - New dimension orthogonal to Status: MoveRequestStatistics.StatusDetail
          (StalledDueToMRS_Quarantined, StalledDueToTarget_*) - a 'Synced' user can
          be quarantined on the MRS side. Shown as an orange sub-badge + clickable
          tile + batch pill + action banner.
        - Synced palette: changed from orange (#c07600) to purple (#6d28d9) so that it
          is no longer confused with the orange Quarantined (close to the error red).
        - Per-batch display: 'average sync %' (average of the user-level
          PercentageComplete) AND '% finalized' shown separately - useful when the
          batch is globally at 95% sync but 0% finalized.

.NOTES
    Author  : Nicolas Fabert
    Version : 2.0.0
    Part of : Exchange 2013/2016 to 2019 Migration - Deploy-Exchange2019.ps1
#>

function Invoke-Step {
    [CmdletBinding()]
    param(
        [string]$Mode,
        [string]$OutputFolder,
        [string]$CsvFolder,
        [hashtable]$Config,
        [System.Management.Automation.PSCredential]$Credential
    )

    # =========================================================================
    # Helper: HTML migration status report
    # =========================================================================
    function New-MigrationStatusHtml {
        # v1.3+: batch-centric report based on Get-MigrationBatch
        # Stats = array of PSCustomObject (see Get-MbSnapshot)
        #   { Name, Status, TotalCount, ActiveCount, SyncedCount, FinalizedCount,
        #     FailedCount, StoppedCount, CreatedDate, CompleteAfter, Users[] }
        param(
            [object[]]$Stats,
            [string]$OutputPath,
            [string]$ReportMode,
            [string]$Title = 'Exchange 2019 migration status',
            # If > 0: adds a browser meta refresh (used by FOLLOW mode).
            [int]$AutoRefreshSeconds = 0
        )

        function Esc {
            param([string]$s)
            if ([string]::IsNullOrEmpty($s)) { return '' }
            $s -replace '&','&amp;' -replace '<','&lt;' -replace '>','&gt;' -replace '"','&quot;'
        }

        # Colors per status (aligned with Exchange: MigrationBatch + MigrationUser)
        # MigrationBatch.Status : Created, Syncing, Synced, Completing, Completed, Failed, Stopped, CompletedWithErrors
        # MigrationUser.Status  : Provisioning, Provisioned, Stopped, Synced, Failed, IncrementalSync, Syncing, Completed, Active
        $clr = @{
            # Green: everything is completed
            'Completed'='var(--cp-success)'; 'CompletedWithErrors'='var(--cp-teal)'
            # Blue: in progress
            'Syncing'='var(--cp-info)'; 'IncrementalSync'='var(--cp-info)'; 'Active'='var(--cp-info)'
            'Provisioning'='var(--cp-info)'; 'Provisioned'='var(--cp-info)'; 'Created'='var(--cp-text-muted)'
            # Orange: waiting for manual completion
            'Synced'='var(--cp-violet)'; 'Completing'='var(--cp-violet)'
            # Red: failure / stopped
            'Failed'='var(--cp-danger)'; 'Stopped'='var(--cp-danger)'
            'default'='var(--cp-text-muted)'
        }
        # Indicators for the display priority (Failed on top, Completed at the bottom)
        $statusSort = @{
            'Failed'=1; 'Stopped'=2
            'Synced'=3; 'Completing'=4
            'Active'=5; 'Syncing'=5; 'IncrementalSync'=5
            'Provisioning'=6; 'Provisioned'=6; 'Created'=7
            'Completed'=8; 'CompletedWithErrors'=8
        }

        $now    = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
        $stamp  = Get-Date -Format 'yyyyMMdd_HHmmss'
        $nbBatch = if ($Stats) { @($Stats).Count } else { 0 }

        # Mapping user status -> displayed group (tile)
        # batch.SyncedCount / FinalizedCount does NOT always reflect the user-level state
        # (Exchange only increments batch.SyncedCount at the batch.Status=Synced transition).
        # So we aggregate from Users[].Status to get exact counters.
        $grpFinal   = @('Completed','CompletedWithErrors')
        $grpSynced  = @('Synced')
        $grpActive  = @('Syncing','IncrementalSync','Active','Provisioning','Provisioned','Created')
        $grpFailed  = @('Failed','Stopped')

        # Quarantined filter: MRS poisoned the move (StalledDueToMRS_*, StalledDueToTarget_*).
        # Criterion: StatusDetail starts with 'Stalled' or contains 'Quarantine'.
        # This predicate is orthogonal to Status (a 'Synced' user can be Quarantined).
        # NB: inline test rather than a shared scriptblock to avoid the
        # 'Cannot overwrite variable u' collision (PS 5.1 optimization scope) with the foreach.

        $allUsers     = @($Stats | ForEach-Object { $_.Users })
        $totalMbx     = @($allUsers).Count
        $totalFinal   = @($allUsers | Where-Object { $_.Status -in $grpFinal  }).Count
        $totalSynced  = @($allUsers | Where-Object { $_.Status -in $grpSynced }).Count
        $totalActive  = @($allUsers | Where-Object { $_.Status -in $grpActive }).Count
        $totalFailed  = @($allUsers | Where-Object { $_.Status -in $grpFailed }).Count
        $totalQuar    = @($allUsers | Where-Object { $_.StatusDetail -and ([string]$_.StatusDetail -match '^Stalled|Quarantine') }).Count
        # Average global progress (user-level PercentageComplete aggregated)
        $globalAvgPct = if ($totalMbx -gt 0) {
            [math]::Round((($allUsers | Measure-Object -Property PercentageComplete -Sum).Sum) / $totalMbx)
        } else { 0 }
        $globalPct = if ($totalMbx -gt 0) { [math]::Round($totalFinal * 100 / $totalMbx) } else { 0 }

        $sb = [System.Text.StringBuilder]::new(250000)

        # ---- HEAD: shared report theme of the module + classes of this report ----
        $extraStyle = @"
.leg{position:relative;display:flex;gap:16px;flex-wrap:wrap;margin-top:14px;font-size:12px;color:var(--cp-text-muted);align-items:center}
.leg-sq{display:inline-block;width:11px;height:11px;border-radius:3px;margin-right:5px;vertical-align:middle}
.acc-step{flex:0 0 auto;min-width:80px}.acc-bar{flex:1;min-width:140px;max-width:260px}
.acc-pct{font-size:12px;font-weight:600;white-space:nowrap;color:var(--cp-text-muted)}.acc-pills{margin-left:auto}
.td-dn{font-weight:600}.td-al{font-size:12px;color:var(--cp-text-muted)}
.mbar{display:flex;height:8px;border-radius:8px;overflow:hidden;background:var(--cp-border);min-width:100px}.mbar-seg{height:8px}
.pbar{display:flex;align-items:center;gap:6px;white-space:nowrap}.pbar-track{background:var(--cp-border);border-radius:8px;height:6px;width:64px;overflow:hidden;flex-shrink:0}
.pbar-fill{height:6px;border-radius:8px}.pbar-lbl{font-size:12px;font-variant-numeric:tabular-nums;min-width:30px}
.banner-manual{display:flex;gap:12px;align-items:flex-start;padding:12px 16px;margin-bottom:20px;border:1px solid var(--cp-border);border-left:4px solid var(--cp-violet);border-radius:.625rem;background:var(--cp-surface)}
.banner-icon{font-size:22px;color:var(--cp-violet);line-height:1}.banner-text{font-size:13px;line-height:1.6}
.batch-action,.batch-warn{padding:10px 16px;font-size:12px;line-height:1.6;border-left:3px solid var(--cp-violet);background:var(--cp-accent-soft)}
.batch-warn{border-left-color:var(--cp-danger)}.batch-warn.quar{border-left-color:var(--cp-warning)}
.filter-state{font-size:12px;font-weight:600;margin-right:6px}.filter-state .clear{margin-left:6px;font-size:12px;padding:2px 10px}
tr.userrow.filter-hidden{display:none}details.batch.filter-empty>summary{opacity:.45}details.batch.filter-empty>:not(summary){display:none}
tr.r-fail td{background:rgba(220,38,38,.07)}tr.r-quar td{background:rgba(217,119,6,.08)}tr.r-sync td{background:rgba(124,58,237,.06)}
tr.r-act td{background:rgba(0,120,212,.05)}tr.r-done td{background:rgba(22,163,74,.05)}
.err-type{color:var(--cp-danger);font-weight:600;font-size:12px}.quar-type{color:var(--cp-warning);font-weight:600;font-size:12px}
.err-msg{font-size:12px;margin-top:3px;white-space:normal;max-width:520px;color:var(--cp-text-muted)}
"@
        [void]$sb.Append((Get-ExHtmlHead -Title ("{0} | {1}" -f $Title, $stamp) -RefreshSeconds $AutoRefreshSeconds -ExtraStyle $extraStyle))

        # ---- HEADER: clickable tiles (data-filter-group = filter of the user rows) ----
        # Clicking a tile filters the users of the report by that group; clicking it again
        # clears the filter (script at the end of the file).
        $tile = {
            param($Class, $Group, $Label, $Value, $Note, $Tone)
            $data  = if ($null -ne $Group) { " data-filter-group='$Group'" } else { '' }
            $style = if ($Tone) { " style='--tone:$Tone'" } else { '' }
            "<article class='$Class'$data$style><span class='tile-label'>$Label</span><strong>$Value</strong><small>$Note</small></article>"
        }
        $refreshText = if ($AutoRefreshSeconds -gt 0) { '<br>Refreshed every {0} min' -f [math]::Round($AutoRefreshSeconds / 60) } else { '' }
        $box = "Mode <strong>$ReportMode</strong><br>$now$refreshText"
        if ($nbBatch -gt 0) {
            $tiles = @(
                (& $tile 'tile tile-primary clickable' 'final' 'Finalized' (Format-ExNumber $totalFinal) ("$globalPct% of $totalMbx mailbox(es)") '')
                (& $tile 'tile clickable' 'synced' 'Synced' (Format-ExNumber $totalSynced) 'Waiting for the manual completion (Step 21)' 'var(--cp-violet)')
                (& $tile 'tile clickable' 'active' 'Active / syncing' (Format-ExNumber $totalActive) 'Created, provisioning or syncing' 'var(--cp-info)')
            )
            if ($totalQuar -gt 0) { $tiles += (& $tile 'tile clickable' 'quarantined' 'Quarantined' (Format-ExNumber $totalQuar) 'Blocked by the Mailbox Replication service' 'var(--cp-warning)') }
            $tiles += (& $tile 'tile clickable' 'failed' 'Failed' (Format-ExNumber $totalFailed) 'Failed or stopped' $(if ($totalFailed -gt 0) { 'var(--cp-danger)' } else { 'var(--cp-success)' }))
            $tiles += (& $tile 'tile tile-tinted' '' 'Batches' (Format-ExNumber $nbBatch) ("$globalAvgPct% average sync") '')
            $extra = "<div class='distribution'>" +
                     "<div><div class='band-head'><span>Average sync</span><span>$globalAvgPct%</span></div><div class='track'><div class='fill' style='width:$globalAvgPct%;background:var(--cp-info)'></div></div></div>" +
                     "<div><div class='band-head'><span>Finalized mailboxes</span><span>$totalFinal / $globalPct%</span></div><div class='track'><div class='fill' style='width:$globalPct%;background:var(--cp-success)'></div></div></div></div>" +
                     "<div class='leg'><span><span class='leg-sq' style='background:var(--cp-success)'></span>Completed / finalized</span>" +
                     "<span><span class='leg-sq' style='background:var(--cp-violet)'></span>Synced (waiting for Step 21)</span>" +
                     "<span><span class='leg-sq' style='background:var(--cp-warning)'></span>Quarantined (MRS blocked)</span>" +
                     "<span><span class='leg-sq' style='background:var(--cp-info)'></span>Syncing / active</span>" +
                     "<span><span class='leg-sq' style='background:var(--cp-text-muted)'></span>Created / provisioning</span>" +
                     "<span><span class='leg-sq' style='background:var(--cp-danger)'></span>Failed / stopped</span>" +
                     "<span class='muted'>Click a tile to filter the mailboxes.</span></div>"
        } else {
            $tiles = @(); $extra = ''
        }
        $subtitle = "$nbBatch migration batch(es), $totalMbx mailbox(es): the state of every batch and every mailbox, from Get-MigrationBatch and the move request statistics (Step 20)."
        [void]$sb.Append((Get-ExHtmlHero -Title $Title -Subtitle $subtitle -BoxLabel 'Status' -BoxHtml $box -Tiles $tiles -ExtraHtml $extra))

        # ---- MANUAL COMPLETION BANNER ---------------------------------------
        # Explicitly states that the batches stay in 'Synced' until
        # Step21 (Complete-MigrationBatch) is launched manually.
        if ($nbBatch -gt 0) {
            [void]$sb.AppendLine("<div class='banner-manual'>")
            [void]$sb.AppendLine("  <span class='banner-icon'>&#9888;</span>")
            [void]$sb.AppendLine("  <div class='banner-text'>")
            [void]$sb.AppendLine("    <strong>MANUAL completion required.</strong>")
            [void]$sb.AppendLine("    The MigrationBatch objects were created with <code>SuspendWhenReadyToComplete</code>:")
            [void]$sb.AppendLine("    the <em>Synced</em> status indicates that a batch is ready to be finalized.")
            [void]$sb.AppendLine("    Run <code>.\Deploy-Exchange2019.ps1 -Step 21 -BatchNumber &lt;NN&gt; -Mode Apply</code>")
            [void]$sb.AppendLine("    (or <code>-BatchNumber ALL</code>) to run <code>Complete-MigrationBatch</code>.")
            [void]$sb.AppendLine("  </div>")
            [void]$sb.AppendLine("</div>")
        }

        if ($nbBatch -eq 0) {
            [void]$sb.AppendLine("<div class='card'><div class='card-hdr'>No data</div>")
            [void]$sb.AppendLine("<div class='card-body muted'>")
            [void]$sb.AppendLine("No <code>Batch\d{2}</code> MigrationBatch found. Run Step19 + Step20 (Apply) to create them.")
            [void]$sb.AppendLine("</div></div>")
            [void]$sb.Append((Get-ExHtmlFooter -Text 'This file contains mailbox addresses: store and share it accordingly.'))
            $sb.ToString() | Set-Content -Path $OutputPath -Encoding UTF8
            return
        }

        # ---- TOOLBAR + ACCORDIONS PER BATCH ---------------------------------
        # No filter buttons here: the filter is carried by the tiles of the header.
        [void]$sb.AppendLine("<div class='toolbar'>")
        [void]$sb.AppendLine("  <span id='filter-state' class='filter-state' style='display:none'></span>")
        [void]$sb.AppendLine("  <span class='label' style='margin:0'>$nbBatch migration batch(es)</span>")
        [void]$sb.AppendLine("  <button class='btn' onclick=""document.querySelectorAll('details.batch:not(.filter-empty)').forEach(function(d){d.open=true})"">&#9660;&thinsp;Expand all</button>")
        [void]$sb.AppendLine("  <button class='btn' onclick=""document.querySelectorAll('details.batch').forEach(function(d){d.open=false})"">&#9650;&thinsp;Collapse all</button>")
        [void]$sb.AppendLine("</div>")

        foreach ($b in ($Stats | Sort-Object Name)) {
            $bName    = [string]$b.Name
            $bStatus  = [string]$b.Status
            # Counters recomputed from Users[] (Exchange's batch.SyncedCount is only
            # incremented at the batch.Status=Synced transition, hence 0 too often).
            $bUsers   = @($b.Users)
            $bTot     = $bUsers.Count
            $bFin     = @($bUsers | Where-Object { $_.Status -in $grpFinal  }).Count
            $bSyn     = @($bUsers | Where-Object { $_.Status -in $grpSynced }).Count
            $bActive  = @($bUsers | Where-Object { $_.Status -in $grpActive }).Count
            $bFld     = @($bUsers | Where-Object { $_.Status -eq 'Failed' }).Count
            $bStopped = @($bUsers | Where-Object { $_.Status -eq 'Stopped' }).Count
            $bQuar    = @($bUsers | Where-Object { $_.StatusDetail -and ([string]$_.StatusDetail -match '^Stalled|Quarantine') }).Count

            # Average batch progress: average of the user-level PercentageComplete.
            # Distinct from $pFin (% of users 100% finalized): a batch where all the users
            # are Synced at 95% gives $bAvgPct=95 but $pFin=0 (none finalized yet).
            $bAvgPct = if ($bTot -gt 0) {
                [math]::Round((($bUsers | Measure-Object -Property PercentageComplete -Sum).Sum) / $bTot)
            } else { 0 }

            # Percentages for the multi-segment bar:
            #   Finalized (green) | Synced (orange = waiting) | Active (blue = in progress) | Failed (red)
            $pFin = if ($bTot -gt 0) { [math]::Round($bFin * 100 / $bTot) } else { 0 }
            $pSyn = if ($bTot -gt 0) { [math]::Round($bSyn * 100 / $bTot) } else { 0 }
            $pAct = if ($bTot -gt 0) { [math]::Round($bActive * 100 / $bTot) } else { 0 }
            $pFld = if ($bTot -gt 0) { [math]::Round($bFld * 100 / $bTot) } else { 0 }

            $barHtml = "<div class='mbar'>"
            if ($pFin -gt 0) { $barHtml += "<div class='mbar-seg' style='width:$pFin%;background:var(--cp-success)' title='Finalized'></div>" }
            if ($pSyn -gt 0) { $barHtml += "<div class='mbar-seg' style='width:$pSyn%;background:var(--cp-violet)' title='Synced (waiting completion)'></div>" }
            if ($pAct -gt 0) { $barHtml += "<div class='mbar-seg' style='width:$pAct%;background:var(--cp-info)' title='Active/Syncing'></div>" }
            if ($pFld -gt 0) { $barHtml += "<div class='mbar-seg' style='width:$pFld%;background:var(--cp-danger)' title='Failed'></div>" }
            $barHtml += "</div>"

            # Pills per counter (priority: Failed > Quarantined > Synced > Active > Finalized)
            $typePills = ''
            if ($bFld -gt 0)     { $typePills += "<span class='pill' style='background:var(--cp-danger)'>Failed&nbsp;$bFld</span>" }
            if ($bStopped -gt 0) { $typePills += "<span class='pill' style='background:var(--cp-danger)'>Stopped&nbsp;$bStopped</span>" }
            if ($bQuar -gt 0)    { $typePills += "<span class='pill' style='background:var(--cp-warning)'>Quarantined&nbsp;$bQuar</span>" }
            if ($bSyn -gt 0)     { $typePills += "<span class='pill' style='background:var(--cp-violet)'>Synced&nbsp;$bSyn</span>" }
            if ($bActive -gt 0)  { $typePills += "<span class='pill' style='background:var(--cp-info)'>Active&nbsp;$bActive</span>" }
            if ($bFin -gt 0)     { $typePills += "<span class='pill' style='background:var(--cp-success)'>Finalized&nbsp;$bFin</span>" }

            $statusColor = if ($clr[$bStatus]) { $clr[$bStatus] } else { $clr['default'] }
            $aid   = 's-' + ($bName -replace '[^a-zA-Z0-9]','-')
            # Auto-open if Failed, Quarantined or Synced (waiting completion = user action required)
            $openA = if ($bFld -gt 0 -or $bQuar -gt 0 -or $bStatus -eq 'Synced') { ' open' } else { '' }

            # "Action required" banner for the Synced / Quarantined / Failed batches
            $actionLine = ''
            if ($bQuar -gt 0) {
                $actionLine = "<div class='batch-warn quar'>&#9888; $bQuar mailbox(es) in MRS quarantine (StalledDueTo*). See details below (StatusDetail). Inspect with <code>Get-MoveRequestStatistics &lt;identity&gt; -IncludeReport</code>.</div>"
            } elseif ($bStatus -eq 'Synced') {
                $batchNum = ($bName -replace '^Batch','') -replace '^0+',''
                $actionLine = "<div class='batch-action'>&#9888; Ready for completion. Run: <code>.\Deploy-Exchange2019.ps1 -Step 21 -BatchNumber $batchNum -Mode Apply</code></div>"
            } elseif ($bFld -gt 0) {
                $actionLine = "<div class='batch-warn'>&#9888; $bFld mailbox(es) in Failed state. See details below (Message + FailureType).</div>"
            }

            [void]$sb.AppendLine("<details$openA id='$aid' class='batch' data-status='$(Esc $bStatus)'>")
            [void]$sb.AppendLine("  <summary>")
            [void]$sb.AppendLine("    <span class='acc-icon'>&#9654;</span>")
            [void]$sb.AppendLine("    <span class='acc-step'>$(Esc $bName)</span>")
            [void]$sb.AppendLine("    <span class='bdg' style='background:$statusColor'>$(Esc $bStatus)</span>")
            [void]$sb.AppendLine("    <span class='acc-cnt'>$bTot&thinsp;mailbox(es)</span>")
            [void]$sb.AppendLine("    <span class='acc-bar'>$barHtml</span>")
            [void]$sb.AppendLine("    <span class='acc-pct' title='Average sync = average PercentageComplete | Finalized = % of users at 100%'>$bAvgPct&thinsp;% sync &middot; $pFin&thinsp;% finalized</span>")
            [void]$sb.AppendLine("    <span class='acc-pills'>$typePills</span>")
            [void]$sb.AppendLine("  </summary>")
            if ($actionLine) { [void]$sb.AppendLine("  $actionLine") }
            [void]$sb.AppendLine("  <div class='tbl-wrap'><table>")
            [void]$sb.AppendLine("    <thead><tr>")
            [void]$sb.AppendLine("      <th style='min-width:240px'>Email / Identity</th>")
            [void]$sb.AppendLine("      <th style='min-width:120px'>Status</th>")
            [void]$sb.AppendLine("      <th style='min-width:130px'>Progress</th>")
            [void]$sb.AppendLine("      <th style='min-width:240px'>Detail / Error</th>")
            [void]$sb.AppendLine("      <th style='min-width:120px'>Target DB</th>")
            [void]$sb.AppendLine("      <th style='min-width:140px'>Last sync</th>")
            [void]$sb.AppendLine("    </tr></thead><tbody>")

            # Sort: Failed first, Completed/Finalized last
            $sortedUsers = @($b.Users) | Sort-Object @{
                Expression = { if ($statusSort[$_.Status]) { $statusSort[$_.Status] } else { 9 } }
            }, Identity

            foreach ($u in $sortedUsers) {
                $uStat = [string]$u.Status
                $sd    = [string]$u.StatusDetail
                $uQuar = $sd -and ($sd -match '^Stalled|Quarantine')
                $bdc   = if ($clr[$uStat]) { $clr[$uStat] } else { $clr['default'] }
                $rbg   = ''
                if ($uStat -in @('Failed','Stopped'))      { $rbg = 'r-fail' }
                elseif ($uQuar)                            { $rbg = 'r-quar' }
                elseif ($uStat -eq 'Synced')               { $rbg = 'r-sync' }
                elseif ($uStat -in @('Syncing','Active','IncrementalSync')) { $rbg = 'r-act' }
                elseif ($uStat -in @('Completed','CompletedWithErrors')) { $rbg = 'r-done' }

                $email = Esc ([string]$u.Identity)
                $pct   = [int]$u.PercentageComplete
                $pctW  = [math]::Min($pct, 100)
                $tdb   = Esc ([string]$u.TargetDatabase)
                $lastU = if ($u.LastUpdateTimestamp) { ([datetime]$u.LastUpdateTimestamp).ToString('yyyy-MM-dd HH:mm') } else { '<span class=em>-</span>' }

                $pbarHtml = "<div class='pbar'><div class='pbar-track'><div class='pbar-fill' style='width:$pctW%;background:$bdc'></div></div><span class='pbar-lbl'>$pct&thinsp;%</span></div>"

                # Status cell: main badge + Quarantined sub-badge (orange) if applicable.
                $statusCell = "<span class='bdg' style='background:$bdc'>$(Esc $uStat)</span>"
                if ($uQuar) {
                    $statusCell += "<div style='margin-top:3px'><span class='bdg' style='background:var(--cp-warning)' title='MoveRequestStatistics.StatusDetail'>$(Esc $sd)</span></div>"
                }

                # Failed error: show FailureType + Message in red.
                # Quarantined: show StatusDetail + MRS Message in orange (warning, not error).
                $detailHtml = if ($uStat -in @('Failed','Stopped')) {
                    $ft  = Esc ([string]$u.FailureType)
                    $msg = Esc ([string]$u.Error)
                    $errBlock = ''
                    if ($ft)  { $errBlock += "<div class='err-type'>$ft</div>" }
                    if ($msg) { $errBlock += "<div class='err-msg'>$msg</div>" }
                    if (-not $errBlock) { $errBlock = "<span class='em'>(no detail)</span>" }
                    $errBlock
                } elseif ($uQuar) {
                    $msg = Esc ([string]$u.Error)
