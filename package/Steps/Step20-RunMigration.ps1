                $b = Get-MigrationBatch -Identity $name -ErrorAction SilentlyContinue
                if ($b) { $out += $b }
            }
            return $out
        }

        $batches = Get-MigrationBatch -ErrorAction SilentlyContinue | Where-Object {
            [string]$_.Identity -match '^Batch\d{2}$'
        }
        if (-not $batches) { return @() }

        # Optional extra filter via MigrationPlan.csv if available (additional defense
        # against names colliding with batches created by hand).
        $planFile = Join-Path $OutputFolder 'MigrationPlan.csv'
        if (Test-Path $planFile) {
            try {
                $rows = Import-Csv $planFile -Delimiter ';' -ErrorAction Stop
                $expected = @($rows | ForEach-Object { 'Batch{0:D2}' -f [int]$_.Batch } | Sort-Object -Unique)
                if ($expected.Count -gt 0) {
                    return @($batches | Where-Object { [string]$_.Identity -in $expected })
                }
            } catch { }
        }
        return @($batches)
    }

