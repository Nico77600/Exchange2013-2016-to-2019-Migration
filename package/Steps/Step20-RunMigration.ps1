    # Distinguish TOTAL MRs (raw, all sources combined) vs MRs DRIVEN
    # by Step19/20 (BatchName filter matching the plan list or regex 'Batch\d{2}').
    # NOTE: MoveRequests created by MigrationBatch have BatchName='MigrationService:BatchNN'.
    # We normalize by stripping the prefix to compare with the official names.
    function Convert-BatchNameToOfficial {
        param([string]$Raw)
        if (-not $Raw) { return '' }
        if ($Raw -match '^MigrationService:(.+)$') { return $matches[1] }
        return $Raw
    }
    $expectedNames    = Get-ExpectedBatchNames
    $inScopeMR        = @($existingMR | Where-Object {
        $_.BatchName -and
        (((Convert-BatchNameToOfficial -Raw $_.BatchName) -match '^Batch\d{2}$') -and
         ($expectedNames -eq $null -or (Convert-BatchNameToOfficial -Raw $_.BatchName) -in $expectedNames))
    })
    $outOfScopeCount  = $existingMR.Count - $inScopeMR.Count

    if ($existingMR.Count -gt 0) {
        Write-Log ("MRs detected: {0} in total - {1} driven by Step19/20 - {2} out of scope (Step18, manual MRs, etc.)" -f `
                   $existingMR.Count, $inScopeMR.Count, $outOfScopeCount) -Level Info
        if ($inScopeMR.Count -gt 0) {
            $snapStats = Get-MrSnapshot
            $byStatus  = $snapStats | Group-Object Status
            foreach ($g in $byStatus) {
                Write-Log "  $($g.Name): $($g.Count)" -Level Info
            }
            if ($Mode -ne 'Inventory') {
                $snapStats | Export-Csv -Path (Join-Path $OutputFolder 'MigrationStatus.csv') `
                    -NoTypeInformation -Encoding UTF8 -Delimiter ';'
            }
        } else {
            Write-Log "  No MR driven by Step19/20 (the report will be empty)." -Level Sub
        }
    } else {
        Write-Log "  No existing MoveRequest." -Level Sub
    }

    # --- Inventory mode (without FOLLOW): snapshot only, no HTML -----------
    if ($Mode -eq 'Inventory' -and -not $followMode) {
        Add-Report -Step '20-Move' -Target 'GLOBAL' -Action 'Snapshot MoveRequest' `
                   -Status Inventoried `
                   -AfterValue ("MRs driven by Step19/20: {0} | Org total: {1} (of which {2} out of scope)" -f `
                                 $inScopeMR.Count, $existingMR.Count, $outOfScopeCount)
        Save-Report -StepName 'Step20-RunMigration' | Out-Null
        return 0
    }

    # --- FOLLOW mode: HTML report + polling loop ----------------------------
    if ($followMode) {
        # Dynamic file name to allow 2 FOLLOW sessions in parallel:
        #  - global Step20 session -Follow  -> MigrationStatus.html
        #  - focus Step21 session -FollowAfter -BatchNumber 01 -> MigrationStatus-Batch01.html
        # Without this suffix, the 2 sessions would overwrite each other (same path).
        $htmlName = switch ($script:followBatchFilters.Count) {
            0       { 'MigrationStatus.html' }
            1       { "MigrationStatus-$($script:followBatchFilters[0]).html" }
            default {
                $sorted = $script:followBatchFilters | Sort-Object
                'MigrationStatus-{0}-{1}.html' -f $sorted[0], $sorted[-1]
            }
        }
        $htmlPath = Join-Path $OutputFolder $htmlName

        # Polling interval (in minutes). Default 60min. Sources by priority:
        #   1. $env:FOLLOW_INTERVAL = '<minutes>'         (session override)
        #   2. $Global:FollowMigrationInterval            (passed by the orchestrator via -FollowInterval)
        #   3. Default 60 minutes
        # Set 0 to generate once without looping.
        $intervalMin = 60
        if ($Global:FollowMigrationInterval -is [int] -and $Global:FollowMigrationInterval -ge 0) {
            $intervalMin = [int]$Global:FollowMigrationInterval
        }
        if ($env:FOLLOW_INTERVAL -match '^\d+$') { $intervalMin = [int]$env:FOLLOW_INTERVAL }
        $refreshSec  = if ($intervalMin -gt 0) { $intervalMin * 60 } else { 0 }

        # ----- 1st generation ------------------------------------------------
        # $snapStats is now an array of MigrationBatch (see Get-MbSnapshot).
        # For the title, we aggregate FinalizedCount / TotalCount over all the batches.
        # In single-batch focus mode (-FollowAfter + -BatchNumber NN), the title
        # explicitly mentions the target batch.
        $titlePrefix = switch ($script:followBatchFilters.Count) {
            0       { 'Migration status' }
            1       { "$($script:followBatchFilters[0]) status (focus)" }
            default { "Status of $($script:followBatchFilters.Count) batches (focus: $($script:followBatchFilters -join ', '))" }
        }
        $titleHtml = if ($snapStats) {
            $tFin = ($snapStats | Measure-Object -Property FinalizedCount -Sum).Sum
            $tTot = ($snapStats | Measure-Object -Property TotalCount     -Sum).Sum
            if (-not $tFin) { $tFin = 0 }; if (-not $tTot) { $tTot = 0 }
            "$titlePrefix - $tFin / $tTot mailbox(es) finalized"
        } else { 'Exchange 2019 migration status' }

        New-MigrationStatusHtml -Stats $snapStats -OutputPath $htmlPath -ReportMode $Mode `
            -Title $titleHtml -AutoRefreshSeconds $refreshSec
        Write-Log "Follow HTML report: $htmlPath" -Level Success

        # Automatic opening in the default browser (1st generation only).
        # The browser then refreshes by itself via meta http-equiv refresh;
        # the following polling iterations do not re-open it (to avoid piling up tabs).
        try {
            Invoke-Item -Path $htmlPath -ErrorAction Stop
            Write-Log "  Opening the HTML in the default browser..." -Level Sub
        } catch {
            Write-Log "  Unable to open the HTML automatically: $($_.Exception.Message)" -Level Warning
        }

        $batchCount = @($snapStats | Where-Object { $_ }).Count
        $tFinSum = ($snapStats | Measure-Object -Property FinalizedCount -Sum).Sum
        $tTotSum = ($snapStats | Measure-Object -Property TotalCount     -Sum).Sum
        if (-not $tFinSum) { $tFinSum = 0 }; if (-not $tTotSum) { $tTotSum = 0 }
        Add-Report -Step '20-Move' -Target 'GLOBAL' -Action 'Follow-Html' -Status Inventoried `
                   -AfterValue $htmlPath `
                   -Detail "Batches=$batchCount | Finalized=$tFinSum/$tTotSum | Interval=${intervalMin}min"
        Save-Report -StepName 'Step20-RunMigration' | Out-Null

        if ($intervalMin -le 0) {
            Write-Log "FOLLOW mode (one-shot, FOLLOW_INTERVAL=0) - HTML generated, exiting." -Level Info
            return 0
        }

        # ----- Polling loop --------------------------------------------------
        # In single-batch focus mode: the loop exits automatically when the target
        # batch reaches a terminal Status (Completed / CompletedWithErrors / Failed).
        # In multi-batch mode: endless loop until Ctrl+C (long-term follow-up).
        Write-Log ("=" * 70) -Level Step
        if ($script:followBatchFilters.Count -eq 1) {
            Write-Log "FOLLOW mode, focus on $($script:followBatchFilters[0]): polling every ${intervalMin}min." -Level Step
            Write-Log "Automatic exit when $($script:followBatchFilters[0]) is Completed (or Ctrl+C)." -Level Sub
        } elseif ($script:followBatchFilters.Count -gt 1) {
            Write-Log ("FOLLOW mode, focus on {0} batches ({1}): polling every {2}min." -f $script:followBatchFilters.Count, ($script:followBatchFilters -join ', '), $intervalMin) -Level Step
            Write-Log "Automatic exit when all the focus batches are Completed (or Ctrl+C)." -Level Sub
        } else {
            Write-Log "FOLLOW mode: polling every ${intervalMin}min. Ctrl+C to exit." -Level Step
        }
        Write-Log "The browser reloads by itself via <meta refresh content='$refreshSec'>." -Level Sub
        Write-Log "To change: `$env:FOLLOW_INTERVAL = '<minutes>' (0=disabled)" -Level Sub
        Write-Log ("=" * 70) -Level Step

        # Terminal statuses that trigger an exit in focus mode
        $terminalStatuses = @('Completed','CompletedWithErrors','Failed')

        $iter = 1
        while ($true) {
            Start-Sleep -Seconds ($intervalMin * 60)
            $iter++
            try {
                $snap = Get-MrSnapshot
                # Aggregation of the mailbox totals over all the MigrationBatch objects
                $tFin = ($snap | Measure-Object -Property FinalizedCount -Sum).Sum
                $tTot = ($snap | Measure-Object -Property TotalCount     -Sum).Sum
                $tSyn = ($snap | Measure-Object -Property SyncedCount    -Sum).Sum
                $tFld = ($snap | Measure-Object -Property FailedCount    -Sum).Sum
                if (-not $tFin) { $tFin = 0 }; if (-not $tTot) { $tTot = 0 }
                if (-not $tSyn) { $tSyn = 0 }; if (-not $tFld) { $tFld = 0 }
                $newTitle = "$titlePrefix - $tFin / $tTot mailbox(es) finalized"

                New-MigrationStatusHtml -Stats $snap -OutputPath $htmlPath -ReportMode $Mode `
                    -Title $newTitle -AutoRefreshSeconds $refreshSec

                Write-Log ("[iter #{0}] {1} - {2} batch(es) | {3}/{4} Finalized | {5} Synced | {6} Failed | HTML refreshed" -f `
                    $iter, (Get-Date -Format 'HH:mm:ss'), @($snap).Count, $tFin, $tTot, $tSyn, $tFld) -Level Info

                # Automatic exit condition in focus mode (single OR multi-batch):
                # all the focus batches must have reached a terminal Status.
                if ($script:followBatchFilters.Count -gt 0 -and @($snap).Count -gt 0) {
                    $focusEntries = @($snap | Where-Object { [string]$_.Name -in $script:followBatchFilters })
                    $focusTerminalCount = @($focusEntries | Where-Object { [string]$_.Status -in $terminalStatuses }).Count
                    if ($focusEntries.Count -eq $script:followBatchFilters.Count -and $focusTerminalCount -eq $script:followBatchFilters.Count) {
                        $detail = ($focusEntries | ForEach-Object { "$([string]$_.Name)=$([string]$_.Status)" }) -join ', '
                        Write-Log ("=" * 70) -Level Step
                        if ($script:followBatchFilters.Count -eq 1) {
                            Write-Log ("Batch {0} reached a terminal Status: {1}" -f $script:followBatchFilters[0], ([string]$focusEntries[0].Status)) -Level Success
                        } else {
                            Write-Log ("All {0} focus batches are in a terminal Status: {1}" -f $script:followBatchFilters.Count, $detail) -Level Success
                        }
                        Write-Log ("Finalized: {0}/{1} | Failed: {2}" -f $tFin, $tTot, $tFld) -Level Sub
                        Write-Log "Final HTML available: $htmlPath" -Level Sub
                        Write-Log "Automatic exit from the FOLLOW loop (focus mode)." -Level Step
                        Write-Log ("=" * 70) -Level Step

                        # Regenerate the HTML without meta refresh (frozen page = "done")
                        New-MigrationStatusHtml -Stats $snap -OutputPath $htmlPath -ReportMode $Mode `
                            -Title $newTitle -AutoRefreshSeconds 0
                        break
                    }
                }
            } catch {
                Write-Log "[iter #$iter] Error: $($_.Exception.Message)" -Level Warning
            }
        }
        return 0
    }

    # =========================================================================
    # APPLY / SIMULATE
    # =========================================================================

    # --- Exchange 2019 databases (round-robin) -------------------------------
    $ex2019Dbs = @(Get-MailboxDatabase -ErrorAction Stop |
                   Where-Object { Test-IsExchange2019Server -ServerName $_.Server.Name })
    $syntheticDbs = $false

    # In Simulate, if Step10 did not really create the databases, we generate the
    # target names from DatabaseLayout to be able to simulate the round-robin.
    # $syntheticDbs=$true signals that the DBs are fictitious -> New-MoveRequest cannot
    # be called even with -WhatIf (the cmdlet validates the TargetDB).
    if (-not $ex2019Dbs -and $Mode -eq 'Simulate' -and $Config.DatabaseLayout) {
        $dl    = $Config.DatabaseLayout
        $pad   = '{0:D' + [int]$dl.DatabaseDigits + '}'
        $names = @(
            for ($i = 0; $i -lt [int]$dl.DatabaseCount; $i++) {
                "$($dl.DatabasePrefix)" + ($pad -f ([int]$dl.DatabaseStartIndex + $i))
            }
        )
        $ex2019Dbs = $names | ForEach-Object { [PSCustomObject]@{ Name = $_ } }
        $syntheticDbs = $true
        Write-Log "No Exchange 2019 database found, generating the names from DatabaseLayout: $($names -join ', ')" -Level Warning
    }

    if (-not $ex2019Dbs) {
        Write-Log "No Exchange 2019 database available." -Level Error
        Save-Report -StepName 'Step20-RunMigration' | Out-Null
        return 1
    }
    Write-Log "Target databases ($($ex2019Dbs.Count)): $($ex2019Dbs.Name -join ', ')" -Level Sub

    # =========================================================================
    # Refactor v1.2: use of New-MigrationBatch -Local instead of individual
    # New-MoveRequest calls. Advantages:
    #   - Appears in EAC > Migration > Batches (centralized management)
    #   - Step21 uses Complete-MigrationBatch (1 command per batch instead of N)
    #   - The report reflects the native Exchange MigrationBatch semantics
    # Limitations:
    #   - PublicFolder mailboxes: not supported by MigrationBatch -Local
    #     -> handled separately via New-MoveRequest -PublicFolder (outside a batch)
    #   - System mailboxes (Arbitration/AuditLog/...): handled by Step18
    # =========================================================================

    # --- Removal: MigrationBatch + orphan MoveRequests -----------------------
    $existingBatches = @(Get-MigrationBatch -ErrorAction SilentlyContinue | Where-Object { $_.Identity -match '^Batch\d{2}$' })
    if ($existingBatches.Count -gt 0) {
        Write-Log "Removing $($existingBatches.Count) existing MigrationBatch(es)..." -Level Step
        foreach ($mb in $existingBatches) {
            $mbName = [string]$mb.Identity
            if ($Mode -eq 'Apply') {
                try {
                    Remove-MigrationBatch -Identity $mbName -Confirm:$false -Force -ErrorAction Stop
                    Add-Report -Step '20-Move' -Target $mbName -Action 'Remove-MigrationBatch' `
                               -Status Success -Detail "Previous status: $($mb.Status)"
                } catch {
                    Write-Log "  Error removing $mbName - $($_.Exception.Message)" -Level Warning
                    Add-Report -Step '20-Move' -Target $mbName -Action 'Remove-MigrationBatch' `
                               -Status Failed -Detail $_.Exception.Message
                }
            } else {
                Add-Report -Step '20-Move' -Target $mbName -Action 'Remove-MigrationBatch' `
                           -Status Simulated -Detail "Status: $($mb.Status)"
            }
        }
    }
    # Orphan MRs (e.g. old submission via direct New-MoveRequest) - we wipe them
    if ($existingMR.Count -gt 0) {
        Write-Log "Removing $($existingMR.Count) orphan MoveRequest(s)..." -Level Step
        foreach ($mr in $existingMR) {
            $mrLabel = if ($mr.DisplayName) { $mr.DisplayName } else { $mr.Alias }
            if ($Mode -eq 'Apply') {
                try {
                    Remove-MoveRequest -Identity $mr.Alias -Confirm:$false -ErrorAction Stop
                    Add-Report -Step '20-Move' -Target $mrLabel -Action 'Remove-MoveRequest (orphan)' `
                               -Status Success -Detail "Previous status: $($mr.Status)"
                } catch {
                    Write-Log "  Error removing $mrLabel - $($_.Exception.Message)" -Level Warning
                }
            }
        }
    }

    # --- Consolidation of the Primary/Archive of the same mailbox in the same batch -
    # If Step19 split the Primary and the Archive of the same mailbox into different
    # batches, we regroup them on the Primary's batch (MigrationBatch does not
    # support a mailbox being in 2 batches simultaneously).
    $primaryByMbx = @{}
    foreach ($row in ($plan | Where-Object { $_.Type -eq 'Primary' })) {
        $primaryByMbx[$row.PrimarySmtpAddress] = [int]$row.Batch
    }
    $consolidated = @()
    foreach ($row in $plan) {
        $effectiveBatch = if ($row.Type -eq 'Archive' -and $primaryByMbx.ContainsKey($row.PrimarySmtpAddress)) {
            [int]$primaryByMbx[$row.PrimarySmtpAddress]
        } else { [int]$row.Batch }
        $consolidated += [PSCustomObject]@{
            Original      = $row
            BatchNum      = $effectiveBatch
            EmailAddress  = $row.PrimarySmtpAddress
            Type          = $row.Type
            RecipientType = $row.RecipientTypeDetails
            Alias         = $row.Alias
        }
    }

    # --- Submission per batch ------------------------------------------------
    $dbIndex   = 0
    $byBatch   = $consolidated | Group-Object BatchNum | Sort-Object { [int]$_.Name }
    foreach ($g in $byBatch) {
        $batchNum  = [int]$g.Name
        $batchName = 'Batch{0:D2}' -f $batchNum

        # Split: PublicFolder vs the rest (PublicFolder -> MoveRequest outside a batch)
        $pfRows  = @($g.Group | Where-Object { $_.RecipientType -eq 'PublicFolderMailbox' })
        $mbxRows = @($g.Group | Where-Object { $_.RecipientType -ne 'PublicFolderMailbox' })

        # Sub-consolidation: for each unique mailbox, we possibly combine
        # Primary + Archive into a single CSV entry with TargetDatabase and
        # TargetArchiveDatabase. Round-robin over the Exchange 2019 databases.
        $csvRows = @()
        $perEmail = $mbxRows | Group-Object EmailAddress
        foreach ($eg in $perEmail) {
            $email = $eg.Name
            $hasPrimary = $eg.Group | Where-Object Type -eq 'Primary'
            $hasArchive = $eg.Group | Where-Object Type -eq 'Archive'

            $tgtPrim = if ($hasPrimary) { $ex2019Dbs[$dbIndex % $ex2019Dbs.Count].Name } else { '' }
            if ($hasPrimary) { $dbIndex++ }
            $tgtArch = if ($hasArchive) { $ex2019Dbs[$dbIndex % $ex2019Dbs.Count].Name } else { '' }
            if ($hasArchive) { $dbIndex++ }

            $csvRows += [PSCustomObject]@{
                EmailAddress          = $email
                TargetDatabase        = $tgtPrim
                TargetArchiveDatabase = $tgtArch
            }
        }

        $detailBatch = "Mailboxes=$($csvRows.Count) | PublicFolder=$($pfRows.Count) | TotalEntries=$($g.Count)"

        if ($syntheticDbs) {
            Add-Report -Step '20-Move' -Target $batchName -Action 'New-MigrationBatch -Local' `
                       -Status Simulated -BeforeValue 'No MigrationBatch (simulated databases from Step10)' `
                       -AfterValue '(simulation - not applied)' -Detail $detailBatch
            continue
        }

        Invoke-Action -Step '20-Move' -Target $batchName -Action 'New-MigrationBatch -Local' `
            -Detail $detailBatch `
            -InventoryScript {
                $b = Get-MigrationBatch -Identity $batchName -ErrorAction SilentlyContinue
                if ($b) { "Status=$($b.Status); TotalCount=$($b.TotalCount)" } else { 'No MigrationBatch' }
            } `
            -PreCheckScript { return $false } `
            -ActionScript {
                if ($csvRows.Count -gt 0) {
                    # New-MigrationBatch -CSVData expects byte[] - we build an in-memory CSV
                    $csvText = ($csvRows | ConvertTo-Csv -NoTypeInformation -Delimiter ',') -join "`r`n"
                    $csvBytes = [System.Text.Encoding]::UTF8.GetBytes($csvText)

                    # Known pitfalls with remoting splat:
                    #   - -AutoStart / -AutoComplete are SWITCHes => do not splat with $false
                    #     (the default for -Local is already $false, so we omit them)
                    #   - -LargeItemLimit splatted with 0 triggers "Parameter set cannot be resolved"
                    #     (internal Exchange validation). We omit it when =0 (Exchange default = 0 anyway).
                    #   - -BadItemLimit splat works even with 0. It can be passed.
                    $params = @{
                        Name         = $batchName
                        Local        = $true
                        CSVData      = $csvBytes
                        BadItemLimit = $badItem
                        ErrorAction  = 'Stop'
                    }
                    if ($largeItem -gt 0) { $params['LargeItemLimit'] = $largeItem }
                    New-MigrationBatch @params -WhatIf:([bool]($Mode -eq 'Simulate')) | Out-Null

                    if ($Mode -eq 'Apply') {
                        Start-MigrationBatch -Identity $batchName -ErrorAction Stop
                        Write-Log "  $batchName - started ($($csvRows.Count) mailbox(es))" -Level Sub
                    }
                }
                # Special case PublicFolder: New-MoveRequest outside a batch (MigrationBatch -Local does not support it)
                foreach ($pf in $pfRows) {
                    $pfAlias = $pf.Alias
                    $pfDb    = $ex2019Dbs[$dbIndex % $ex2019Dbs.Count].Name
                    $dbIndex++
                    $pfParams = @{
                        Identity                   = $pfAlias
                        BatchName                  = $batchName
                        TargetDatabase             = $pfDb
                        PublicFolder               = $true
                        SuspendWhenReadyToComplete = $true
                        BadItemLimit               = $badItem
                        LargeItemLimit             = $largeItem
                        AcceptLargeDataLoss        = $acceptLDL
                        ErrorAction                = 'Stop'
                    }
                    New-MoveRequest @pfParams -WhatIf:([bool]($Mode -eq 'Simulate')) | Out-Null
                    Write-Log "  $batchName - PublicFolder $pfAlias -> $pfDb (via New-MoveRequest)" -Level Sub
                }
            }
    }

    # --- Final snapshot + HTML (Apply) ---------------------------------------
    # We use Get-MbSnapshot to get the batch-centric shape (see helper above).
    # The HTML now expects this shape (one PSCustomObject per MigrationBatch with Users[]).
    if ($Mode -eq 'Apply') {
        Start-Sleep -Seconds 3
        $final = Get-MbSnapshot

        # CSV: we flatten per user to keep a usable CSV format
        $csvRows = foreach ($b in $final) {
            foreach ($u in $b.Users) {
                [PSCustomObject]@{
                    Batch              = $b.Name
                    BatchStatus        = $b.Status
                    Identity           = $u.Identity
                    UserStatus         = $u.Status
                    PercentComplete    = $u.PercentageComplete
                    TargetDatabase     = $u.TargetDatabase
                    Error              = $u.Error
                    FailureType        = $u.FailureType
                    LastUpdate         = $u.LastUpdateTimestamp
                    SkippedItems       = $u.SkippedItemCount
                }
            }
        }
        $csvPath = Join-Path $OutputFolder 'MigrationStatus.csv'
        $csvRows | Export-Csv -Path $csvPath -NoTypeInformation -Encoding UTF8 -Delimiter ';'
        Add-Report -Step '20-Move' -Target 'GLOBAL' -Action 'Export-Csv (final)' `
                   -Status Success -AfterValue $csvPath

        $htmlPath = Join-Path $OutputFolder 'MigrationStatus.html'
        New-MigrationStatusHtml -Stats $final -OutputPath $htmlPath -ReportMode $Mode `
                                -Title 'Migration started - initial report'
        Write-Log "Migration HTML report: $htmlPath" -Level Success
        Add-Report -Step '20-Move' -Target 'GLOBAL' -Action 'Export-Html' `
                   -Status Success -AfterValue $htmlPath -Detail 'Initial report after submission'
    }

    Save-Report -StepName 'Step20-RunMigration' | Out-Null
    return 0
}
