    # Local helper: full snapshot for the HTML report, batch-centric structure.
    # Returns an array of PSCustomObject, one per official MigrationBatch:
    #   { Name, Status, TotalCount, ActiveCount, SyncedCount, FinalizedCount,
    #     FailedCount, StoppedCount, CreatedDate, CompleteAfter, Users[] }
    # Users[] contains one entry per mailbox of the batch with:
    #   { Identity, Mail, DisplayName, Status, PercentageComplete, Error,
    #     LastUpdateTimestamp, TargetDatabase, SkippedItemCount }
    #
    # Source: Get-MigrationBatch (batch-level) + Get-MigrationUser | Get-MigrationUserStatistics
    # (mailbox-level). Enriched with Get-MoveRequestStatistics to get
    # TargetDatabase (not exposed on MigrationUserStatistics).
    function Get-MbSnapshot {
        $batches = Get-OfficialMigrationBatches
        if ($batches.Count -eq 0) { return @() }

        # Local helper: strip the "MigrationService:" prefix to normalize to the official name
        $normBatch = { param($n) if ($n -match '^MigrationService:(.+)$') { $matches[1] } else { [string]$n } }

        # Lookup of TargetDatabase via Get-MoveRequestStatistics. WARNING: the MRs created
        # by MigrationBatch have BatchName='MigrationService:BatchNN', hence the extended regex.
        #
        # OPTIMIZATION single-batch focus: if $script:followBatchFilter is set,
        # we filter directly server-side via -BatchName 'MigrationService:BatchNN'.
        # Without this filter, Get-MoveRequest serializes ALL the MRs of the organization
        # (5+ min for 455 MRs), versus ~1-2s for ~40 MRs. The server-side filter avoids the
        # full round-trip + serialization.
        if ($script:followBatchFilters.Count -gt 0) {
            $allMrs = @()
            foreach ($name in $script:followBatchFilters) {
                $mrs = Get-MoveRequest -BatchName ("MigrationService:" + $name) -ErrorAction SilentlyContinue
                if ($mrs) { $allMrs += $mrs }
            }
        } else {
            $allMrs = Get-MoveRequest -ErrorAction SilentlyContinue |
                      Where-Object { $_.BatchName -and ((& $normBatch $_.BatchName) -match '^Batch\d{2}$') }
        }

        # MigrationUser.Identity is the email (UPN/SMTP); MoveRequest.Alias is the AD alias.
        # When the AD alias != the local part of the email (e.g. 'jdupont' vs 'jean.dupont@...'),
        # an index on the alias alone misses the match -> TargetDb and MR % are lost.
        # So we resolve alias->email via Get-Recipient (script: cache so as not to
        # pay the remoting round-trips again on each HTML refresh).
        if (-not $script:_mbSnapAliasEmailCache) { $script:_mbSnapAliasEmailCache = @{} }
        $aliasToEmail = $script:_mbSnapAliasEmailCache

        $mrStats = @()
        if ($allMrs) {
            $toResolve = @($allMrs | Where-Object {
                $_.Alias -and -not $aliasToEmail.ContainsKey([string]$_.Alias)
            })
            foreach ($mr in $toResolve) {
                try {
                    $rec = Get-Recipient -Identity ([string]$mr.Identity) -ErrorAction Stop
                    if ($rec -and $rec.PrimarySmtpAddress) {
                        $aliasToEmail[[string]$mr.Alias] = ([string]$rec.PrimarySmtpAddress).ToLower()
                    }
                } catch { }
            }

            $mrStats = @($allMrs | Get-MoveRequestStatistics -ErrorAction SilentlyContinue |
                Select-Object DisplayName, Alias, BatchName, TargetDatabase, Status, StatusDetail, PercentComplete,
                              Message, FailureType, LastUpdateTimestamp)
        }
        # Double index: 'Batch01||email::xxx' (preferred) + 'Batch01||alias::xxx' (fallback)
        $mrByKey = @{}
        foreach ($s in $mrStats) {
            $normName = & $normBatch $s.BatchName
            $alias    = [string]$s.Alias
            $mrByKey["$normName||alias::$($alias.ToLower())"] = $s
            if ($aliasToEmail.ContainsKey($alias)) {
                $mrByKey["$normName||email::$($aliasToEmail[$alias])"] = $s
            }
        }

        $snapshot = @()
        foreach ($b in $batches) {
            $bid = [string]$b.Identity
            $users = Get-MigrationUser -BatchId $bid -ErrorAction SilentlyContinue
            $userStats = @()
            if ($users) {
                $userStats = @($users | Get-MigrationUserStatistics -ErrorAction SilentlyContinue)
            }
            $userRows = foreach ($u in $userStats) {
                $email      = ([string]$u.Identity).ToLower()
                $aliasGuess = if ($email -match '^([^@]+)@') { $matches[1] } else { $email }
                # Cascading lookup: email first (key resolved via Get-Recipient),
                # alias derived from the local part of the email as a fallback.
                $mrInfo = $mrByKey["$bid||email::$email"]
                if (-not $mrInfo) { $mrInfo = $mrByKey["$bid||alias::$aliasGuess"] }

                $tgtDb      = if ($mrInfo) { [string]$mrInfo.TargetDatabase } else { '' }
                $errMsg     = if ($u.Error) { [string]$u.Error } else { '' }
                if (-not $errMsg -and $mrInfo -and $mrInfo.Message) { $errMsg = [string]$mrInfo.Message }
                $failType   = if ($mrInfo) { [string]$mrInfo.FailureType } else { '' }
                $lastUpdate = if ($u.LastSuccessfulSyncTime) { $u.LastSuccessfulSyncTime } `
                              elseif ($mrInfo) { $mrInfo.LastUpdateTimestamp } `
                              else { $null }
                # PercentComplete: MoveRequestStatistics is the reliable source.
                # MigrationUserStatistics.PercentComplete often stays at 0 even when Synced.
                $pct = 0
                if ($mrInfo -and [int]$mrInfo.PercentComplete -gt 0) { $pct = [int]$mrInfo.PercentComplete }
                elseif ($u.PercentComplete) { $pct = [int]$u.PercentComplete }
                # Safety net: a Synced/Completed user without a % is necessarily >= 95%
                if ($pct -eq 0) {
                    $st = [string]$u.Status
                    if ($st -in @('Completed','CompletedWithErrors')) { $pct = 100 }
                    elseif ($st -eq 'Synced') { $pct = 95 }
                }

                # StatusDetail comes from MoveRequestStatistics (e.g. StalledDueToMRS_Quarantined,
                # StalledDueToTarget_DiskLatency...): essential to spot the users
                # blocked on the MRS side while MigrationUser.Status stays 'Synced'.
                $statusDetail = if ($mrInfo -and $mrInfo.StatusDetail) { [string]$mrInfo.StatusDetail } else { '' }

                [PSCustomObject]@{
                    Identity            = $email
                    Alias               = $aliasGuess
                    DisplayName         = [string]$u.RecipientType + ' - ' + $email   # MigrationUser does not expose DisplayName directly
                    Status              = [string]$u.Status
                    StatusDetail        = $statusDetail
                    PercentageComplete  = $pct
                    Error               = $errMsg
                    FailureType         = $failType
                    LastUpdateTimestamp = $lastUpdate
                    TargetDatabase      = $tgtDb
                    SkippedItemCount    = [int]$u.SkippedItemCount
                }
            }

            # If some mailboxes have an MR but no MigrationUser (e.g. PublicFolder
            # via New-MoveRequest outside a MigrationBatch), we attach them to the batch via
            # their BatchName label.
            $mrOnly = $mrStats | Where-Object {
                $_.BatchName -eq $bid -and
                -not ($userStats | Where-Object { ([string]$_.Identity -split '@')[0] -ieq [string]$_.Alias })
            }
            foreach ($mr in $mrOnly) {
                $userRows += [PSCustomObject]@{
                    Identity            = [string]$mr.Alias
                    Alias               = [string]$mr.Alias
                    DisplayName         = [string]$mr.DisplayName
                    Status              = [string]$mr.Status
                    StatusDetail        = [string]$mr.StatusDetail
                    PercentageComplete  = [int]$mr.PercentComplete
                    Error               = [string]$mr.Message
                    FailureType         = [string]$mr.FailureType
                    LastUpdateTimestamp = $mr.LastUpdateTimestamp
                    TargetDatabase      = [string]$mr.TargetDatabase
                    SkippedItemCount    = 0
                }
            }

            $snapshot += [PSCustomObject]@{
                Name           = $bid
                Status         = [string]$b.Status
                TotalCount     = [int]$b.TotalCount
                ActiveCount    = [int]$b.ActiveCount
                SyncedCount    = [int]$b.SyncedCount
                FinalizedCount = [int]$b.FinalizedCount
                FailedCount    = [int]$b.FailedCount
                StoppedCount   = [int]$b.StoppedCount
                CreatedDate    = $b.CreationDateTime
                CompleteAfter  = $b.CompleteAfter
                Users          = @($userRows)
            }
        }
        return $snapshot
    }

    # Backward-compatible alias: the old code called Get-MrSnapshot, we keep the name
