    # Local helper: returns the list of official MigrationBatch objects (Step20).
    # Source of truth = Get-MigrationBatch (native Exchange object). Filtered by
    # name matching 'Batch\d{2}' (Step20 convention). Can additionally be
    # cross-checked against the plan via MigrationPlan.csv, and restricted to a single batch
    # via $script:followBatchFilter (focus mode -FollowAfter + -BatchNumber NN).
    function Get-OfficialMigrationBatches {
        # OPTIMIZATION single/multi-batch focus: Get-MigrationBatch -Identity targets
        # each batch directly, avoids serializing all the MigrationBatch objects of the org.
        if ($script:followBatchFilters.Count -gt 0) {
            $out = @()
